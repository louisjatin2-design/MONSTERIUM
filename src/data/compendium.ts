// ──────────────────────────────────────────────────────────────────────────
// Compendium: the full Monster-Legends-style catalogue of traits and battle
// effects. This is REFERENCE DATA — a browsable glossary surfaced in the
// Kompendium screen — kept deliberately separate from the small set of traits
// and status effects the battle engine actually wires up (see traits.ts /
// statusEffects.ts). Adding an entry here makes it visible and documented in
// the game without destabilising the combat code.
// ──────────────────────────────────────────────────────────────────────────

export interface CompendiumEntry {
  name: string;
  description: string;
  // Default duration in turns, as shown in-game. A string so ranges ("1-3"),
  // alternatives ("2 or 4") and non-applied effects ("—") read naturally.
  turns?: string;
}

export interface CompendiumGroup {
  id: string;
  title: string;   // German section title
  icon: string;
  color: string;
  entries: CompendiumEntry[];
}

